"""Маскирование персональных данных в тексте, который уходит внешней модели.

Ученик может сам написать имя, телефон или школу. Правила намеренно простые: они снижают
риск утечки, но не гарантируют полного удаления. Годы, классы и баллы ЕГЭ не трогаем.
"""

import re

_NAME = r"[А-ЯЁ][а-яё]+(?:-[А-ЯЁ][а-яё]+)?"
_ORG = r"(?:школ[аеуы]|школой|лице[йюяе]|лицеем|гимнази[яиюей]{1,2})"

_RULES: tuple[tuple[re.Pattern[str], str], ...] = (
    (re.compile(r"[\w.+-]+@[\w-]+(?:\.[\w-]+)+"), "[email]"),
    (
        re.compile(r"(?:https?://)?(?:www\.)?(?:vk\.com|t\.me|max\.ru|ok\.ru)/[\w./-]+", re.I),
        "[контакт]",
    ),
    (re.compile(r"(?<![\w@])@[A-Za-z][\w.]{3,}"), "[контакт]"),
    (re.compile(r"(?<![\d+])(?:\+7|8|7)[\s\-()]*(?:\d[\s\-()]*){9}\d(?!\d)"), "[телефон]"),
    # «меня зовут Вася Иванов», «моё имя Вася»
    (
        re.compile(
            rf"((?:[Мм]еня\s+зовут|[Зз]овут\s+меня|[Мм]о[её]\s+имя(?:\s*[-—:])?)\s+){_NAME}"
            rf"(?:\s+{_NAME}){{0,2}}"
        ),
        r"\1[имя]",
    ),
    # «я Вася Иванов»: одно слово с большой буквы слишком часто оказывается не именем
    (re.compile(rf"(\b[Яя]\s+){_NAME}\s+{_NAME}(?:\s+{_NAME})?"), r"\1[имя]"),
    # «школа № 57», «лицей 239», «57-й школы»
    (re.compile(rf"\b{_ORG}\s*(?:№|номер|N)?\s*\d+", re.I), "[школа]"),
    (re.compile(rf"\b\d+(?:-?[а-я]{{1,3}})?\s+{_ORG}\b", re.I), "[школа]"),
)


def mask_personal_data(text: str) -> str:
    """Заменяет телефоны, e-mail, контакты, имя и номер школы на метки."""
    for pattern, replacement in _RULES:
        text = pattern.sub(replacement, text)
    return text
