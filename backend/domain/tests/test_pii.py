import pytest
from olymp_domain.pii import mask_personal_data


@pytest.mark.parametrize(
    ("text", "expected"),
    [
        ("пиши на vasya.ivanov@mail.ru", "пиши на [email]"),
        ("почта ivanov2009@yandex.ru", "почта [email]"),
        ("мой телефон +7 (916) 123-45-67", "мой телефон [телефон]"),
        ("звони 89161234567!", "звони [телефон]!"),
        ("пиши в WhatsApp: +79161234567", "пиши в WhatsApp: [телефон]"),
        ("мой номер 8 (916) 123-45-67", "мой номер [телефон]"),
        ("тел. 8-916-123-45-67", "тел. [телефон]"),
        ("я в vk.com/vasya2009", "я в [контакт]"),
        ("профиль https://vk.com/id12345", "профиль [контакт]"),
        ("пиши в t.me/olymp_helper", "пиши в [контакт]"),
        ("мой ник @vasya_2009", "мой ник [контакт]"),
        ("Иванов Иван Иванович просит помочь", "[имя] просит помочь"),
        ("Иванов И.И. сдал диплом", "[имя] сдал диплом"),
        ("СНИЛС 123-456-789 12", "СНИЛС [снилс]"),
        ("снилс 12345678912", "снилс [снилс]"),
        ("паспорт 4501 123456", "паспорт [паспорт]"),
        ("паспорт 45 01 123456", "паспорт [паспорт]"),
        ("ИНН 7707083893", "ИНН [инн]"),
        ("ИНН 770708389312", "ИНН [инн]"),
        ("живу на ул. Ленина, д. 5", "живу на [адрес]"),
        ("адрес: улица Пушкина, дом 10", "адрес: [адрес]"),
        ("дата рождения 12.05.2010", "дата рождения [дата]"),
        ("родился 2010-05-12", "родился [дата]"),
        ("Меня зовут Вася Иванов, 10 класс", "Меня зовут [имя], 10 класс"),
        ("моё имя Анна-Мария", "моё имя [имя]"),
        ("Привет, я Вася Иванов", "Привет, я [имя]"),
        ("учусь в школе № 57", "учусь в [школа]"),
        ("ученик лицея 239", "ученик [школа]"),
        ("я из 57-й школы", "я из [школа]"),
        ("школа № 1543", "[школа]"),
        ("лицей 1535", "[школа]"),
        ("гимназия №5", "[школа]"),
        ("2025 89161234567", "2025 [телефон]"),
        ("баллы 85 и 90, тел. 89161234567", "баллы 85 и 90, тел. [телефон]"),
    ],
)
def test_masks_personal_data(text: str, expected: str) -> None:
    assert mask_personal_data(text) == expected


@pytest.mark.parametrize(
    "text",
    [
        "10 класс, призёр НТО 2025 года",
        "ЕГЭ: математика 85, информатика 90, русский 78",
        "Всероссийская олимпиада школьников по физике",
        "хочу в ВШЭ на ПМИ, профиль 01.03.02",
        "я Призёр",
        "ищу олимпиады для школы",
        "победитель олимпиады «Физтех» по математике",
        "планирую поступать в МФТИ на бюджет",
        "призёр Высшей пробы по математике 10 класс",
        "ЕГЭ 85 баллов",
        "Летняя школа 2025",
        "Летняя Школа 2025",
        "школа 2025",
        "школа 1998 года",
        "школе 10 класса",
        "ЕГЭ: математика 85, информатика 90, русский 78",
        "в 2025 году баллы 85 и 90",
    ],
)
def test_keeps_ordinary_text(text: str) -> None:
    assert mask_personal_data(text) == text
