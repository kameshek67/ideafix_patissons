"""Разговорные названия вузов: «Вышка», «Бауманка», «Физтех» находят свой вуз в поиске."""

# разговорное название -> кусок официального названия (без учёта регистра)
NICKNAMES: dict[str, str] = {
    "вышка": "ВШЭ",
    "высшая школа экономики": "ВШЭ",
    "бауманка": "Баумана",
    "бауманское": "Баумана",
    "физтех": "МФТИ",
    "политех": "СПбПУ",
    "питерский политех": "СПбПУ",
    "плешка": "Плеханова",
    "мифи": "МИФИ",
    "питерский универ": "СПбГУ",
    "питерский университет": "СПбГУ",
    "петербургский университет": "СПбГУ",
    "сеченовка": "Сеченов",
    "пироговка": "Пирогова",
    "керосинка": "Губкина",
    "мгимо": "МГИМО",
    "финашка": "Финансовый университет",
    "финуниверситет": "Финансовый университет",
}

MIN_LENGTH = 3


def fold(text: str) -> str:
    return " ".join(text.lower().replace("ё", "е").split())


def name_fragments(q: str) -> list[str]:
    """Куски названий, которые подходят под разговорный запрос: «выш» -> [«ВШЭ»]."""
    needle = fold(q)
    if len(needle) < MIN_LENGTH:
        return []
    return list(dict.fromkeys(part for nick, part in NICKNAMES.items() if needle in fold(nick)))


def nicknames_of(name: str) -> list[str]:
    """Разговорные названия вуза — фронт ищет и по ним."""
    low = name.lower()
    return [nick for nick, part in NICKNAMES.items() if part.lower() in low]
